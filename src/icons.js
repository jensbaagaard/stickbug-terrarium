// An SVG path filling each '#' with a unit square.
export const pixelPath = (rows) =>
  rows.flatMap((row, y) => [...row].map((c, x) => (c === '#' ? `M${x} ${y}h1v1h-1z` : ''))).join('');

// An icon as a CSS cursor at twice its size, light with a dark outline so it shows over anything, its hotspot at
// pixel (x, y).
const cursor = (rows, x, y, fallback) => {
  const d = pixelPath(rows);
  const [w, h] = [rows[0].length + 2, rows.length + 2];
  const at = (x, y) => `transform="translate(${x + 1} ${y + 1})" d="${d}"`;
  const outline = [-1, 0, 1].flatMap((dx) => [-1, 0, 1].map((dy) => `<path ${at(dx, dy)}/>`)).join('');
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" width="${w * 2}" height="${h * 2}" viewBox="0 0 ${w} ${h}" ` +
    `shape-rendering="crispEdges"><g fill="#17110c">${outline}</g><path ${at(0, 0)} fill="#e3d3b5"/></svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}") ${(x + 1) * 2} ${(y + 1) * 2}, ${fallback}`;
};

export const SCISSORS_CURSOR = cursor(ICONS.prune, 4, 4, 'crosshair');
